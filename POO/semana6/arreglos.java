public class arreglos {
    public static void main(String[] args) {
        //Creacion del arreglo
        int[] a = {6, 5, 9, 1, 8 , 3, 2,};

        //recorrer y mostrar el arreglo
        for (int i = 0; i < a.length; i++) {
            System.out.println("a [" + i + "]: " + a[i]);
        }
        
    }
}
